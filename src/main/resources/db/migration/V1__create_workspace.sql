-- The shared activity log. Every context appends to it; space_id lets reads keep to the spaces a caller may see.
CREATE TABLE activities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind VARCHAR(60) NOT NULL,
    actor_kind VARCHAR(10) NOT NULL,
    actor_user_id UUID,
    actor_login VARCHAR(39),
    actor_connection_id UUID,
    actor_client_name VARCHAR(200),
    space_id UUID,
    document_id UUID,
    thread_id UUID,
    revision INT,
    summary VARCHAR(300) NOT NULL,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_activities_actor_kind CHECK (actor_kind IN ('HUMAN', 'AGENT', 'SYSTEM'))
);

CREATE INDEX ix_activities_space ON activities (space_id, id);
CREATE INDEX ix_activities_occurred ON activities (occurred_at);

-- Owned by the workspace context from here on. Former slugs stay reserved so old addresses keep redirecting.
-- Column names avoid SQL keywords such as name, path, and source: Exposed quotes those in lower case, which does
-- not match H2's upper-case columns.
CREATE TABLE spaces (
    id UUID PRIMARY KEY,
    slug VARCHAR(50) NOT NULL,
    space_name VARCHAR(100) NOT NULL,
    description VARCHAR(500) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_spaces_slug UNIQUE (slug)
);

CREATE TABLE space_former_slugs (
    slug VARCHAR(50) PRIMARY KEY,
    space_id UUID NOT NULL,
    slug_position INT NOT NULL,
    CONSTRAINT fk_space_former_slugs_space FOREIGN KEY (space_id) REFERENCES spaces (id)
);

CREATE TABLE space_links (
    space_id UUID NOT NULL,
    link_position INT NOT NULL,
    kind VARCHAR(30) NOT NULL,
    link_value VARCHAR(2000) NOT NULL,
    CONSTRAINT pk_space_links PRIMARY KEY (space_id, link_position),
    CONSTRAINT fk_space_links_space FOREIGN KEY (space_id) REFERENCES spaces (id)
);

-- body is the annotated markdown of the blocks: the lossless canonical form, which keeps block, row, and column ids.
-- active_path equals doc_path outside the trash and is null inside it, so only live documents compete for a path.
-- search_text is the lowercase title and plain text for substring search. tags are stored as " a b " so a tag
-- filter is a LIKE on " tag ".
CREATE TABLE documents (
    id UUID PRIMARY KEY,
    space_id UUID NOT NULL,
    doc_path VARCHAR(300) NOT NULL,
    active_path VARCHAR(300),
    title VARCHAR(200) NOT NULL,
    status VARCHAR(20) NOT NULL,
    tags VARCHAR(1000) NOT NULL,
    assignee VARCHAR(39),
    body TEXT NOT NULL,
    search_text TEXT NOT NULL,
    revision INT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    trashed_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_documents_space FOREIGN KEY (space_id) REFERENCES spaces (id),
    CONSTRAINT uk_documents_active_path UNIQUE (space_id, active_path),
    CONSTRAINT ck_documents_status CHECK (status IN ('DRAFT', 'IN_REVIEW', 'CONFIRMED', 'ARCHIVED')),
    CONSTRAINT ck_documents_revision CHECK (revision >= 1)
);

CREATE INDEX ix_documents_space_updated ON documents (space_id, updated_at);

-- Full content at each revision. Rows are never updated, except the latest one while its author keeps typing.
CREATE TABLE document_revisions (
    document_id UUID NOT NULL,
    revision INT NOT NULL,
    space_id UUID NOT NULL,
    doc_path VARCHAR(300) NOT NULL,
    title VARCHAR(200) NOT NULL,
    status VARCHAR(20) NOT NULL,
    tags VARCHAR(1000) NOT NULL,
    assignee VARCHAR(39),
    body TEXT NOT NULL,
    trashed BOOLEAN NOT NULL,
    actor_kind VARCHAR(10) NOT NULL,
    actor_user_id UUID NOT NULL,
    actor_login VARCHAR(39) NOT NULL,
    actor_connection_id UUID,
    actor_client_name VARCHAR(200),
    change_source VARCHAR(10) NOT NULL,
    summary VARCHAR(200) NOT NULL,
    changed_blocks TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_document_revisions PRIMARY KEY (document_id, revision),
    CONSTRAINT fk_document_revisions_document FOREIGN KEY (document_id) REFERENCES documents (id)
);

-- The latest change to each block still in the document, for the "changed by Claude 2 minutes ago" marker.
CREATE TABLE document_block_marks (
    document_id UUID NOT NULL,
    block_id VARCHAR(16) NOT NULL,
    revision INT NOT NULL,
    actor_kind VARCHAR(10) NOT NULL,
    actor_user_id UUID NOT NULL,
    actor_login VARCHAR(39) NOT NULL,
    actor_connection_id UUID,
    actor_client_name VARCHAR(200),
    changed_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_document_block_marks PRIMARY KEY (document_id, block_id),
    CONSTRAINT fk_document_block_marks_document FOREIGN KEY (document_id) REFERENCES documents (id)
);

-- One row per person, document, and day, for the "came back to it on another day" metric.
CREATE TABLE document_views (
    document_id UUID NOT NULL,
    viewer_login VARCHAR(39) NOT NULL,
    viewed_on DATE NOT NULL,
    CONSTRAINT pk_document_views PRIMARY KEY (document_id, viewer_login, viewed_on),
    CONSTRAINT fk_document_views_document FOREIGN KEY (document_id) REFERENCES documents (id)
);

-- Anchors are resolved against the current document when read, so edits never rewrite threads. author_kind copies
-- the first comment's author kind for filtering.
CREATE TABLE threads (
    id UUID PRIMARY KEY,
    space_id UUID NOT NULL,
    document_id UUID NOT NULL,
    anchor_kind VARCHAR(10) NOT NULL,
    anchor_block VARCHAR(16),
    anchor_row VARCHAR(16),
    anchor_column VARCHAR(16),
    anchor_start INT,
    anchor_end INT,
    anchor_quote VARCHAR(2000),
    anchored_revision INT NOT NULL,
    status VARCHAR(10) NOT NULL,
    author_kind VARCHAR(10) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    resolved_at TIMESTAMP WITH TIME ZONE,
    resolver_kind VARCHAR(10),
    resolver_user_id UUID,
    resolver_login VARCHAR(39),
    resolver_connection_id UUID,
    resolver_client_name VARCHAR(200),
    CONSTRAINT fk_threads_document FOREIGN KEY (document_id) REFERENCES documents (id),
    CONSTRAINT ck_threads_anchor_kind CHECK (anchor_kind IN ('TEXT', 'CELL', 'BLOCK', 'DOCUMENT')),
    CONSTRAINT ck_threads_status CHECK (status IN ('OPEN', 'ANSWERED', 'RESOLVED'))
);

CREATE INDEX ix_threads_document ON threads (document_id, created_at);
CREATE INDEX ix_threads_space_updated ON threads (space_id, updated_at);

CREATE TABLE thread_comments (
    id UUID PRIMARY KEY,
    thread_id UUID NOT NULL,
    comment_position INT NOT NULL,
    author_kind VARCHAR(10) NOT NULL,
    author_user_id UUID NOT NULL,
    author_login VARCHAR(39) NOT NULL,
    author_connection_id UUID,
    author_client_name VARCHAR(200),
    body TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    deleted_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_thread_comments_thread FOREIGN KEY (thread_id) REFERENCES threads (id),
    CONSTRAINT uk_thread_comments_position UNIQUE (thread_id, comment_position)
);

CREATE TABLE comment_edits (
    comment_id UUID NOT NULL,
    edit_position INT NOT NULL,
    previous_body TEXT NOT NULL,
    edited_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_comment_edits PRIMARY KEY (comment_id, edit_position),
    CONSTRAINT fk_comment_edits_comment FOREIGN KEY (comment_id) REFERENCES thread_comments (id)
);

CREATE TABLE comment_mentions (
    comment_id UUID NOT NULL,
    login VARCHAR(39) NOT NULL,
    CONSTRAINT pk_comment_mentions PRIMARY KEY (comment_id, login),
    CONSTRAINT fk_comment_mentions_comment FOREIGN KEY (comment_id) REFERENCES thread_comments (id)
);

CREATE TABLE thread_revisions (
    thread_id UUID NOT NULL,
    revision INT NOT NULL,
    CONSTRAINT pk_thread_revisions PRIMARY KEY (thread_id, revision),
    CONSTRAINT fk_thread_revisions_thread FOREIGN KEY (thread_id) REFERENCES threads (id)
);

-- recipient is a lowercase GitHub login.
CREATE TABLE inbox_items (
    id UUID PRIMARY KEY,
    recipient VARCHAR(39) NOT NULL,
    kind VARCHAR(20) NOT NULL,
    space_id UUID NOT NULL,
    document_id UUID NOT NULL,
    thread_id UUID NOT NULL,
    comment_id UUID NOT NULL,
    actor_kind VARCHAR(10) NOT NULL,
    actor_user_id UUID NOT NULL,
    actor_login VARCHAR(39) NOT NULL,
    actor_connection_id UUID,
    actor_client_name VARCHAR(200),
    excerpt VARCHAR(200) NOT NULL,
    delivered_at TIMESTAMP WITH TIME ZONE NOT NULL,
    read_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT ck_inbox_items_kind CHECK (kind IN ('MENTION', 'REPLY', 'ASSIGNED_COMMENT'))
);

CREATE INDEX ix_inbox_items_recipient ON inbox_items (recipient, delivered_at);

-- The bytes live in object storage under sha256. The same bytes are one asset per space.
CREATE TABLE assets (
    id UUID PRIMARY KEY,
    space_id UUID NOT NULL,
    media_type VARCHAR(10) NOT NULL,
    size_bytes BIGINT NOT NULL,
    sha256 VARCHAR(64) NOT NULL,
    file_name VARCHAR(200) NOT NULL,
    source_url VARCHAR(2000),
    uploader_kind VARCHAR(10) NOT NULL,
    uploader_user_id UUID NOT NULL,
    uploader_login VARCHAR(39) NOT NULL,
    uploader_connection_id UUID,
    uploader_client_name VARCHAR(200),
    uploaded_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_assets_space FOREIGN KEY (space_id) REFERENCES spaces (id),
    CONSTRAINT uk_assets_content UNIQUE (space_id, sha256)
);

-- What a write with an operation id produced, so a retry answers with the first result.
CREATE TABLE write_operations (
    writer VARCHAR(60) NOT NULL,
    operation_id VARCHAR(100) NOT NULL,
    kind VARCHAR(40) NOT NULL,
    target_id UUID NOT NULL,
    revision INT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_write_operations PRIMARY KEY (writer, operation_id)
);
